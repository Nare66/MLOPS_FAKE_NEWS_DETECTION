import os
from fastapi import APIRouter, HTTPException, Depends
from fastapi.responses import HTMLResponse, FileResponse
from backend.app.schemas import MonitoringResponse
from backend.app.services.monitoring_service import MonitoringService
from backend.app.services.model_service import model_service
from backend.app.config import settings

router = APIRouter(tags=["MLOps Monitoring & Drift"])

@router.get("/monitoring", response_model=MonitoringResponse)
def get_monitoring_metrics():
    """
    Get Evidently AI data drift and model monitoring metrics.
    Compares reference baseline data against production inference batches.
    """
    summary = MonitoringService.get_latest_monitoring()
    model_info = model_service.get_info()
    
    return MonitoringResponse(
        drift_detected=summary.get("drift_detected", False),
        drift_score=summary.get("drift_score", 0.0),
        status=summary.get("status", "STABLE"),
        dataset_version=summary.get("dataset_version", "v1.0.0"),
        current_model_version=model_info.get("active_version", "v1.0.0"),
        last_monitoring_run=summary.get("run_date", "2026-10-30 00:00:00"),
        reference_sample_count=summary.get("reference_samples", 42),
        current_sample_count=summary.get("current_samples", 35),
        column_drift_details=summary.get("column_drift_details", {}),
        report_available=os.path.exists(summary.get("report_html_path", ""))
    )

@router.get("/monitoring/report")
def get_monitoring_html_report():
    """
    Serve the full interactive HTML report generated by Evidently AI.
    """
    summary = MonitoringService.get_latest_monitoring()
    report_path = summary.get("report_html_path")
    
    if not report_path or not os.path.exists(report_path):
        # Look for any html file in reports dir
        reports = [os.path.join(settings.REPORTS_DIR, f) for f in os.listdir(settings.REPORTS_DIR) if f.endswith(".html")]
        if reports:
            report_path = sorted(reports)[-1]
        else:
            raise HTTPException(status_code=404, detail="No Evidently AI monitoring report generated yet.")

    return FileResponse(report_path, media_type="text/html")

@router.post("/monitoring/run", response_model=MonitoringResponse)
def trigger_monitoring_run():
    """
    Execute an on-demand Evidently AI drift analysis cycle.
    """
    summary = MonitoringService.run_monitoring()
    model_info = model_service.get_info()
    
    return MonitoringResponse(
        drift_detected=summary.get("drift_detected", False),
        drift_score=summary.get("drift_score", 0.0),
        status=summary.get("status", "STABLE"),
        dataset_version=summary.get("dataset_version", "v1.0.0"),
        current_model_version=model_info.get("active_version", "v1.0.0"),
        last_monitoring_run=summary.get("run_date", "2026-10-30 00:00:00"),
        reference_sample_count=summary.get("reference_samples", 42),
        current_sample_count=summary.get("current_samples", 35),
        column_drift_details=summary.get("column_drift_details", {}),
        report_available=os.path.exists(summary.get("report_html_path", ""))
    )
